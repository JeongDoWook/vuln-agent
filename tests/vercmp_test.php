<?php
declare(strict_types=1);

/**
 * vercmp 단위 테스트 — 배포판 버전 비교.
 *
 * 기대값은 **실제 도구에서 뽑았다**(추측 아님):
 *   deb : dpkg --compare-versions A lt|gt B         (php:8.3-cli 컨테이너에 dpkg 내장)
 *   rpm : rpm --eval '%{lua:print(rpm.vercmp(A,B))}' (rockylinux:9)
 *   apk : apk version -t A B                        (alpine:3.19)
 *   go  : golang.org/x/mod/semver.Compare(A,B)      (golang:1.22-alpine + x/mod v0.17.0)
 *   lang/upstream : node -e 'require("semver").compare(A,B)'
 *
 * 실행:
 *   docker run --rm -v "$PWD:/w" -w /w php:8.3-cli php tests/vercmp_test.php
 */

require_once __DIR__ . '/../server/src/vercmp.php';

$fail = 0;
$run = static function (string $label, array $cases, callable $fn) use (&$fail): void {
    foreach ($cases as [$a, $b, $want]) {
        $got = $fn($a, $b);
        if ($got !== $want) {
            printf("  ✗ [%s] %s vs %s → 기대 %d, 실제 %d\n", $label, $a, $b, $want, $got);
            $fail++;
        }
    }
};

// dpkg — epoch, 릴리스, 틸드(~), binNMU(+b1), 데비안 리비전
$run('deb', [
    ['1.1.1f-1ubuntu2.19', '1.1.1f-1ubuntu2.20', -1],
    ['1.1.1f-1ubuntu2.19', '1.1.1f-1ubuntu2.9',   1],  // 19 > 9 (문자열이면 반대)
    ['1:1.1.1',            '2.0',                 1],  // epoch 우선
    ['1.0~rc1',            '1.0',                -1],  // 틸드는 이전
    ['1.0',                '1.0-1',              -1],
    ['2.30-3',             '2.30-3+deb11u1',     -1],
    ['1.2.3-4+b1',         '1.2.3-4',             1],  // binNMU
    ['0:1.0',              '1.0',                 0],
    ['5.4.0-150.167',      '5.4.0-90.101',        1],
    ['1.10',               '1.9',                 1],
    ['1.0-1',              '1.0-1~bpo11+1',       1],  // 백포트는 이전
    ['3.0.11-1~deb12u2',   '3.0.11-1~deb12u1',    1],
    ['2.38-1',             '2.38-1',              0],
    ['7.88.1-10+deb12u5',  '7.88.1-10+deb12u12', -1],
], static fn(string $a, string $b): int => vg_ver_cmp($a, $b, 'dpkg'));

// rpm — rpmvercmp 구간 비교(숫자/문자, ~, ^)
$run('rpm-frag', [
    ['1.1.1k',            '1.1.1k',             0],
    ['12.el8_9',          '9.el8',              1],
    ['1.0~rc1',           '1.0',               -1],
    ['97.el7',            '97.el7_9.1',        -1],
    ['513.24.1.el8_9',    '477.27.1.el8_8',     1],
    ['1',                 '1.1',               -1],
    ['1.0^20240101',      '1.0',                1],  // ^ 는 이후
    ['0.4.0',             '0.4',                1],
    ['1.0a',              '1.0',                1],
    ['2.el9',             '2.el9_4',           -1],
    ['1.0',               '1.0.0',             -1],
], 'vg_rpm_cmp_frag');

// rpm — 전체 EVR. rpm -qa 는 에포크가 없으면 "(none)" 을 찍는다 → 0 으로 봐야 한다.
$run('rpm-evr', [
    ['(none):1.2-3',            '1.2-3',                   0],
    ['1:1.2-3',                 '2.0-1',                   1],   // epoch 우선
    ['1.1.1k-12.el8_9',         '1.1.1k-9.el8',            1],
    ['4.18.0-513.24.1.el8_9',   '4.18.0-477.27.1.el8_8',   1],
    ['1.0-1',                   '1.0-1.1',                -1],
], static fn(string $a, string $b): int => vg_ver_cmp($a, $b, 'rpm'));

// 언어 패키지(semver/PEP440). 기대값은 실제 npm semver 라이브러리에서 뽑았다:
//   node -e 'require("semver").compare(a,b)'
$run('lang', [
    ['2.19.1',       '2.31.0',        -1],   // requests: 취약 → 조치
    ['1.0.0-rc1',    '1.0.0',         -1],   // 프리릴리스는 정식보다 이전
    ['2.0.0',        '10.0.0',        -1],   // 숫자 비교(문자열이면 반대)
    ['1.2.3',        '1.2.3',          0],
    ['4.17.20',      '4.17.21',       -1],
    ['1.0.0-beta.2', '1.0.0-beta.11', -1],
    ['1.0.1',        '1.0.0',          1],
], static fn(string $a, string $b): int => vg_ver_cmp($a, $b, 'npm'));

// apk(알파인) — 리비전(-rN)·프리릴리스 접미사(_alpha/_beta/_pre/_rc)·포스트릴리스(_p/_git).
// 기대값은 alpine:3.19 의 `apk version -t A B` 에서 뽑았다. 접미사 순서도 그 도구로 전수 확인했다:
//   _alpha < _beta < _pre < _rc < (접미사 없음) < _cvs < _svn < _git < _hg < _p
$run('apk', [
    ['1.2.3-r0',     '1.2.3-r1',     -1],
    ['1.2.3-r10',    '1.2.3-r9',      1],   // 10 > 9 (문자열이면 반대)
    ['1.2.3-r0',     '1.2.3-r0',      0],
    ['1.0',          '1.0.1',        -1],
    ['0.9.8',        '0.10.1',       -1],   // 자릿수 비교
    ['2.10',         '2.9',           1],
    ['1.2.3-r0',     '1.2.4-r0',     -1],
    ['1.0_alpha1',   '1.0_beta1',    -1],
    ['1.0_beta1',    '1.0_pre1',     -1],
    ['1.0_pre1',     '1.0_rc1',      -1],
    ['1.0_rc1',      '1.0',          -1],   // ★ dpkg 규칙이면 1 이 나와 rc 를 오억제(미탐)했다
    ['1.0_alpha1',   '1.0',          -1],
    ['1.0_beta1',    '1.0',          -1],
    ['1.0_pre1',     '1.0',          -1],
    ['1.0_rc1',      '1.0_rc2',      -1],
    ['1.0_rc1',      '1.0_rc10',     -1],
    ['1.0',          '1.0_p1',       -1],   // 포스트릴리스는 정식보다 이후
    ['1.0_git',      '1.0',           1],
    ['1.0_p1',       '1.0_git',       1],   // _git < _p
    ['1.0_rc1-r1',   '1.0-r0',       -1],   // 리비전보다 접미사가 먼저다
    ['1.2.3_rc1-r2', '1.2.3_rc1-r1',  1],   // 접미사가 같으면 리비전으로
    ['1.2.3a',       '1.2.3',         1],   // 뒤에 붙는 문자
    ['1.0',          '1.0.0',        -1],   // 자리 수가 모자란 쪽이 이전
    ['1.0',          '1.0-r0',       -1],   // 리비전 없음 < -r0
], static fn(string $a, string $b): int => vg_ver_cmp($a, $b, 'apk'));

// Go 모듈. 이 분기의 존재 이유는 'v' 접두 제거다 — OSV 조치안은 'v' 없이 온다.
// 기대값은 golang.org/x/mod/semver.Compare 에서 뽑았다(정규화한 뒤의 쌍으로 물었다:
// 오라클은 'v' 없는 "1.2.3" 을 무효로 보고 항상 크다고 답하므로 그대로는 오라클이 못 된다).
$run('go', [
    ['v1.2.3',                            '1.2.3',           0],   // ★ v 접두만 다르면 같은 버전
    ['v1.2.3',                            'v1.2.3',          0],
    ['v1.2.3',                            'v1.2.4',         -1],
    ['v1.2.3',                            'v1.2.10',        -1],   // 자릿수 비교
    ['v2.0.0',                            'v10.0.0',        -1],
    ['v1.0.0-rc1',                        'v1.0.0',         -1],   // 프리릴리스는 정식보다 이전
    ['v1.0.0-beta.2',                     'v1.0.0-beta.11', -1],
    ['v0.0.0-20210101120000-abcdef123456', 'v0.1.0',        -1],   // 의사 버전(pseudo-version)
    ['v1.0.0+incompatible',               'v1.0.0',          0],   // 빌드 메타데이터는 우선순위에서 무시
    ['v2.1.0+incompatible',               '2.1.0',           0],   // 실제 SBOM ↔ OSV 조치안 꼴
], static fn(string $a, string $b): int => vg_ver_cmp($a, $b, 'go'));

// 업스트림 앱 버전(컨테이너 바이너리에서 뽑은 nginx 등 ↔ OSV Bitnami).
// 기대값은 npm semver.compare 에서 뽑았다(lang 그룹과 같은 오라클).
$run('upstream', [
    ['1.28.2',    '1.28.10',  -1],   // 자릿수 비교(문자열이면 반대)
    ['1.24.0',    '1.25.3',   -1],
    ['1.25.3',    '1.24.0',    1],
    ['1.21.0',    '1.21.0',    0],
    ['3.0.11',    '3.0.9',     1],
    ['2.0.0',     '10.0.0',   -1],
    ['1.0.0-rc1', '1.0.0',    -1],
    // 부분 버전은 semver 오라클이 거부한다(Invalid Version: 1.21) — 기대값을 뽑을 곳이 없어
    // **현행 동작을 고정**해 회귀만 잡는다. 방향은 오탐 쪽(설치본을 더 낮게 봐 억제하지 않음)이라
    // 안전하다. 바꾸려면 "부분 버전을 어떻게 채울지"부터 오라클로 정해야 한다.
    ['1.21',      '1.21.0',   -1],
], static fn(string $a, string $b): int => vg_ver_cmp($a, $b, 'upstream'));

if ($fail === 0) {
    echo "vercmp: 전체 통과\n";
    exit(0);
}
printf("vercmp: %d건 실패\n", $fail);
exit(1);
