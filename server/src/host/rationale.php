<?php
declare(strict_types=1);

/**
 * host/rationale.php — 판정 근거 문장을 **표에 실을 때만** 짧게 줄인다(표시 층).
 *
 *   매처가 저장한 근거(tb_finding.rationale)는 한 문장에 판정의 모든 축을 담는다:
 *     "외부노출(systemd:111 가 libc6 사용) → HIGH · CISA KEV 등재
 *      · 벤더 미수정(우분투 보안 OVAL: 수정본 미배포) — 조치 불가(수정본 없음)"
 *   그런데 자산 상세의 표에서는 그중 셋이 **같은 행의 다른 칸이 이미 말한 것**이다 —
 *   등급('등급·상태' 칸), KEV(같은 칸의 뱃지), 그리고 "조치 불가(수정본 없음)"은
 *   바로 앞의 "벤더 미수정"과 같은 말이다. 46행이 전부 같은 꼬리를 달고 있으면 그 열은
 *   행마다 다른 값(어느 프로세스가 무엇을 물고 있나)을 읽기 어려워진다.
 *
 *   **근거를 없애는 게 아니라 중복만 접는다.** 원문은 행을 눌러 여는 상세 모달의
 *   '판정 근거'에 그대로 있고(vuln 탭이 data-finding-detail 로 실어 보낸다),
 *   판정 근거 화면(/vendor.php)도 그대로다. 매처·억제 로직은 건드리지 않는다.
 */
function vg_host_rationale_brief(?string $why): string {
    $s = trim((string) $why);
    if ($s === '') { return ''; }
    // 등급 — 같은 행의 '등급·상태' 칸(그 값이 상수면 표 위 한 줄)이 이미 말한다.
    $s = preg_replace('/\s*→\s*(CRITICAL|HIGH|MEDIUM|LOW)\b/u', '', $s) ?? $s;
    // KEV — 같은 칸에 뱃지로 선다.
    $s = preg_replace('/\s*·\s*CISA KEV 등재/u', '', $s) ?? $s;
    // 출처 부기(어느 피드가 그렇게 말했나)는 행마다 같다 — 열 머리글과 상세 모달이 맡는다.
    $s = preg_replace('/(벤더 미수정)\s*\([^()]*\)/u', '$1', $s) ?? $s;
    // "벤더 미수정"과 "조치 불가(수정본 없음)"은 한 셀에서 같은 말을 두 번 하는 것이다.
    $s = preg_replace('/\s*—\s*조치 불가\(수정본 없음\)/u', '', $s) ?? $s;
    // 앞뒤에 남은 구분자(· — 공백)를 정리한다. trim() 은 바이트 단위라 여기 쓰지 않는다.
    $s = preg_replace('/^[\s·—]+|[\s·—]+$/u', '', $s) ?? $s;
    return $s;
}
