#!/usr/bin/env bash
# =============================================================================
# block-dev-stack.sh — dev 스택 up/down 직접 실행 차단 (PreToolUse 훅)
# =============================================================================
# CLAUDE.md 가 "에이전트는 dev up -d 를 실행하지 않는다" 를 여러 번 문서로 적어뒀지만,
# 문서는 강제력이 없다 — 과거 세션들이 그 문구를 무시하고 직접 커맨드를 쳐서 dev 스택을
# 자기 트리로 끌어오는 바람에 다른 세션의 스모크·작업이 계속 끊겼다. 이 훅이 그 문서 규칙을
# 코드로 강제한다(block-main-push.sh 와 같은 패턴).
#
# web+scheduler 가 워크트리별로 독립 컨테이너로 뜨게 된 뒤에도(compose.dev.yml/compose.dev-db.yml
# 분리) 이 차단은 그대로 유지한다 — 이제는 "서로 스택을 뺏는다"는 옛 이유는 없어졌지만,
# "컨테이너 기동/중지는 항상 사람이 명시적으로 한다" 는 이 저장소 전체의 원칙은 트리 격리 여부와
# 무관하게 유효하다(에이전트가 반사적으로 컨테이너를 올렸다 내렸다 하며 리소스를 쓰는 것 자체를
# 막는다). 완화하려면 이 파일을 고치는 게 아니라 CLAUDE.md 가드레일부터 사용자와 합의한다.
#
# 동작: Bash/PowerShell 도구 호출 직전, 커맨드에서 compose_runner.sh/.ps1 를 dev 환경의
#   up/down 서브커맨드로 부르는 패턴을 감지하면 exit 2 로 차단한다.
#   dev doctor/init/logs/ps, prod(운영 배포)는 막지 않는다 — 이 훅은 "dev 스택 기동/전환"만
#   금지 대상이다(CLAUDE.md 가드레일과 동일 범위).
# =============================================================================
INPUT=$(cat)

if printf '%s' "$INPUT" | grep -qE 'compose_runner\.(sh|ps1)[^|;&\n]*\bdev\b[^|;&\n]*\b(up|down)\b'; then
  echo "🚫 dev 컨테이너 기동/전환(dev up|down) 차단 — 컨테이너 기동/중지는 항상 사용자가 직접 한다." >&2
  echo "   (web+scheduler 가 워크트리별로 독립돼도 이 원칙은 그대로다.) 필요하면 사용자에게 요청하고 기다리세요." >&2
  exit 2
fi

exit 0
